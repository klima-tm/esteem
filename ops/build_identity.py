#!/usr/bin/env python3
"""Build the shared runtime identity from the maintained knowledge files."""
import argparse
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ('COMMUNICATION.md', 'COMPANY.md', 'PRICING.md', 'DROPBOX_GUIDE.md')

def build():
    sections = []
    for name in SOURCES:
        content = (ROOT / 'knowledge' / name).read_text(encoding='utf-8').strip()
        if not content:
            raise ValueError(f'Knowledge source is empty: {name}')
        sections.append(content)
    return ('# Esteem.Pro — единый контекст агента\n\n'
            '<!-- Generated by ops/build_identity.py. Edit knowledge/COMMUNICATION.md, '
            'knowledge/COMPANY.md, knowledge/PRICING.md and knowledge/DROPBOX_GUIDE.md, then rebuild. -->\n\n'
            + '\n\n---\n\n'.join(sections) + '\n')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--check', action='store_true', help='Check that AGENT.md matches its sources')
    group.add_argument('--reload', action='store_true', help='Rebuild and restart the Esteem WhatsApp gateway')
    args = parser.parse_args()
    output = ROOT / 'AGENT.md'
    expected = build()
    current = output.read_text(encoding='utf-8') if output.exists() else ''
    if args.check:
        if current != expected:
            raise SystemExit('AGENT.md is out of date; run python3 ops/build_identity.py --reload')
        print('AGENT.md matches all source files.')
        return
    if current != expected:
        mode = output.stat().st_mode & 0o777 if output.exists() else 0o600
        name = None
        try:
            with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=ROOT, delete=False) as f:
                name = f.name
                f.write(expected)
                f.flush()
                os.fsync(f.fileno())
            os.chmod(name, mode)
            os.replace(name, output)
        finally:
            if name and os.path.exists(name):
                os.unlink(name)
        print('Rebuilt AGENT.md from knowledge source files.')
    else:
        print('AGENT.md is already current.')
    if args.reload:
        subprocess.run(['systemctl', 'restart', 'esteem-hermes.service'], check=True)
        print('Reloaded the WhatsApp gateway. Telegram and MAX read AGENT.md for each reply.')

if __name__ == '__main__':
    main()
